"""One-time (and re-runnable) setup. Run it as ./setup.sh from the repo root.

1. .env from .env.example (your settings: ports, Home Assistant, allowlists)
2. app-secrets.env: one random STRATUM_APP_SECRET_<ID> per app backend
3. compose.apps.yml: includes apps/<id>/compose.yml for every app backend
   that's set up (an app whose manifest "requiresEnv" names an empty .env
   setting is left out, with a note; STRATUM_APPS_OFF=home,ssh skips some)
4. data/ folders, owned by you (Docker would make them root's)
5. a TLS certificate (WebXR needs HTTPS): mkcert if installed, else openssl

.env, app-secrets.env and data/ hold secrets: all three are gitignored.
Standard library only, so it runs before any venv exists.
"""
import json
import os
import re
import secrets
import shutil
import socket
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV, EXAMPLE, SECRETS, INCLUDES = ROOT / ".env", ROOT / ".env.example", ROOT / "app-secrets.env", ROOT / "compose.apps.yml"
DATA = ROOT / "data"


def env_key(app_id):
    return app_id.upper().replace("-", "_")


def read_env(path):
    out = {}
    if path.exists():
        for line in path.read_text().splitlines():
            m = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)=(.*)$", line)
            if m:
                out[m[1]] = m[2].strip().strip('"').strip("'")
    return out


def set_env(path, key, value):
    """Set KEY=value in an env file, keeping everything else (and comments)."""
    lines = path.read_text().splitlines() if path.exists() else []
    for i, line in enumerate(lines):
        if re.match(rf"^\s*{key}=", line):
            lines[i] = f"{key}={value}"
            break
    else:
        lines.append(f"{key}={value}")
    path.write_text("\n".join(lines) + "\n")


def say(msg):
    print(f"  {msg}")


def lan_ips():
    ips = []
    try:
        ips = subprocess.run(["hostname", "-I"], capture_output=True, text=True).stdout.split()
    except OSError:
        pass
    if not ips:   # macOS: no `hostname -I`
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
                s.connect(("10.255.255.255", 1))
                ips = [s.getsockname()[0]]
        except OSError:
            pass
    return [ip for ip in ips if ":" not in ip]   # IPv4 first is what phones type


def host_timezone():
    p = Path("/etc/timezone")
    if p.exists():
        return p.read_text().strip()
    link = Path("/etc/localtime")
    if link.is_symlink():
        return str(link.resolve()).split("zoneinfo/", 1)[-1]
    return os.environ.get("TZ")


def backend_apps():
    """Apps with a compose.yml, as (id, manifest)."""
    out = []
    for compose in sorted((ROOT / "apps").glob("*/compose.yml")):
        manifest = json.loads((compose.parent / "manifest.json").read_text())
        out.append((manifest["id"], manifest))
    return out


def step_env():
    if not ENV.exists():
        shutil.copy(EXAMPLE, ENV)
        ENV.chmod(0o600)
        say("made .env from .env.example (edit it to turn on Home Assistant / SSH)")
    env = read_env(ENV)
    # Inside Docker, "localhost" is the container: reach the host's HA via the gateway.
    if re.match(r"^https?://(localhost|127\.0\.0\.1)", env.get("HA_URL", "")):
        set_env(ENV, "HA_URL", re.sub(r"//(localhost|127\.0\.0\.1)", "//host.docker.internal", env["HA_URL"]))
        say("HA_URL: localhost → host.docker.internal (seen from the container)")
    if hasattr(os, "getuid"):
        set_env(ENV, "STRATUM_UID", str(os.getuid()))
        set_env(ENV, "STRATUM_GID", str(os.getgid()))
    set_env(ENV, "COMPOSE_FILE", "docker-compose.yml:compose.apps.yml")
    if not env.get("TZ"):   # the browser app's Chrome shows pages your timezone
        tz = host_timezone()
        if tz:
            set_env(ENV, "TZ", tz)
            say(f"TZ: {tz}")
    return read_env(ENV)


def step_secrets(env, apps):
    have = read_env(SECRETS)
    lines = ["# Generated by ./setup.sh: the secret each app backend shares with Stratum.",
             "# Stratum reads all of them; each backend gets only its own. Not in git."]
    for app_id, _ in apps:
        key = f"STRATUM_APP_SECRET_{env_key(app_id)}"
        # Older setups kept these in .env as <ID>_SECRET: keep the value.
        value = have.get(key) or env.get(f"{env_key(app_id)}_SECRET") or secrets.token_hex(32)
        lines.append(f"{key}={value}")
    SECRETS.write_text("\n".join(lines) + "\n")
    SECRETS.chmod(0o600)
    say(f"app-secrets.env: {len(apps)} app backends")


def step_includes(env, apps):
    off = {a.strip() for a in env.get("STRATUM_APPS_OFF", "").split(",") if a.strip()}
    on, skipped = [], []
    for app_id, manifest in apps:
        missing = [k for k in manifest.get("requiresEnv", []) if not env.get(k)]
        if app_id in off:
            skipped.append(f"{app_id} (STRATUM_APPS_OFF)")
        elif missing:
            skipped.append(f"{app_id} (set {', '.join(missing)} in .env)")
        else:
            on.append(app_id)
    body = ["# Generated by ./setup.sh: the app backends to run. Re-run it after adding",
            "# an app (e.g. `git submodule add <url> apps/<id>`) or changing .env.",
            "include:"]
    for app_id in on:
        body += [f"  - path: apps/{app_id}/compose.yml", "    env_file: [.env, app-secrets.env]"]
    if not on:
        body[-1] = "include: []"
    INCLUDES.write_text("\n".join(body) + "\n")
    say(f"backends on: {', '.join(on) or 'none'}")
    for s in skipped:
        say(f"backend off: {s}")


def step_data(apps):
    for d in [DATA, *[DATA / "apps" / a for a, _ in apps]]:
        d.mkdir(parents=True, exist_ok=True)


def step_cert():
    cert, key = DATA / "cert.pem", DATA / "key.pem"
    if cert.exists():
        say("certificate: data/cert.pem (kept; delete it and re-run to remake)")
        return
    names = ["localhost", "127.0.0.1", socket.gethostname(), *lan_ips()]
    if shutil.which("mkcert"):
        subprocess.run(["mkcert", "-cert-file", str(cert), "-key-file", str(key), *names], check=True, capture_output=True)
        caroot = subprocess.run(["mkcert", "-CAROOT"], capture_output=True, text=True).stdout.strip()
        say(f"certificate: mkcert, for {', '.join(names)}")
        say(f"  trust it on the headset/phone: install {caroot}/rootCA.pem there (README → Setup, part 2)")
    elif shutil.which("openssl"):
        san = ",".join(f"IP:{n}" if re.match(r"^[\d.]+$", n) else f"DNS:{n}" for n in names)
        subprocess.run(["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "825",
                        "-keyout", str(key), "-out", str(cert), "-subj", "/CN=stratum",
                        "-addext", f"subjectAltName={san}"], check=True, capture_output=True)
        say("certificate: self-signed (browsers warn once; install mkcert for no warning)")
    else:
        sys.exit("Need mkcert or openssl to make the HTTPS certificate WebXR requires.")
    key.chmod(0o600)


def main():
    print("Stratum setup")
    if not shutil.which("docker"):
        say("note: Docker not found. ./run.sh still runs the core without app backends.")
    env = step_env()
    apps = backend_apps()
    step_secrets(env, apps)
    step_includes(env, apps)
    step_data(apps)
    step_cert()
    port = env.get("STRATUM_PORT", "8930")
    ip = (lan_ips() or ["localhost"])[0]
    print(f"""
Next:
  docker compose up -d --build
  then open https://{ip}:{port} in Quest Browser (or Chrome on an ARCore phone).
  Print markers from https://{ip}:{port}/tags.html (README → Setup, part 2).""")


if __name__ == "__main__":
    main()
